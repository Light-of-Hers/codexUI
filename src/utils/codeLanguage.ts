export const HIGHLIGHT_LANGUAGE_ALIASES: Record<string, string[]> = Object.entries(
  HIGHLIGHT_LANGUAGE_CANONICAL_BY_ALIAS,
).reduce((aliases, [alias, language]) => {
  if (alias === language) return aliases
  aliases[language] = [...(aliases[language] ?? []), alias]
  return aliases
}, {} as Record<string, string[]>)

function normalizeLanguageToken(value: string): string {
  const token = value.trim().split(/\s+/u)[0]?.toLowerCase() ?? ''
  return token
}

function basenameFromPath(pathValue: string): string {
  const normalizedPath = pathValue.trim().replace(/\\/gu, '/').replace(/\/+$/u, '')
  if (!normalizedPath) return ''
  const slashIndex = normalizedPath.lastIndexOf('/')
  return slashIndex >= 0 ? normalizedPath.slice(slashIndex + 1) : normalizedPath
}

function extnameFromPath(pathValue: string): string {
  const base = basenameFromPath(pathValue)
  if (!base) return ''
  const lastDotIndex = base.lastIndexOf('.')
  if (lastDotIndex <= 0) return ''
  return base.slice(lastDotIndex).toLowerCase()
}

function resolveLanguageForPath(
  pathValue: string,
  byBasename: Record<string, string>,
  byExtension: Record<string, string>,
): string {
  const normalizedPath = pathValue.trim()
  if (!normalizedPath) return 'plaintext'

  const normalizedBasename = basenameFromPath(normalizedPath).toLowerCase()
  const basenameLanguage = byBasename[normalizedBasename]
  if (basenameLanguage) return basenameLanguage

  const extension = extnameFromPath(normalizedPath)
  return byExtension[extension] ?? 'plaintext'
}

export function getEditorModeForPath(pathValue: string): string {
  return resolveLanguageForPath(pathValue, EDITOR_LANGUAGE_BY_BASENAME, EDITOR_LANGUAGE_BY_EXTENSION)
}

export function getHighlightLanguageForPath(pathValue: string): string {
  return resolveLanguageForPath(pathValue, HIGHLIGHT_LANGUAGE_BY_BASENAME, HIGHLIGHT_LANGUAGE_BY_EXTENSION)
}

export function normalizeHighlightLanguage(language: string): string {
  const token = normalizeLanguageToken(language)
  if (!token) return ''
  return HIGHLIGHT_LANGUAGE_CANONICAL_BY_ALIAS[token] ?? token
}

